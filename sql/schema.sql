
BEGIN;

-- =========================================================
-- Players
-- =========================================================

CREATE TABLE IF NOT EXISTS players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle VARCHAR(50) NOT NULL UNIQUE,
    display_name VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_players_handle_length
        CHECK (length(trim(handle)) BETWEEN 1 AND 50)
);

-- =========================================================
-- Matches
-- =========================================================

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_time TIMESTAMPTZ NOT NULL,

    home_team VARCHAR(100),
    home_player_id BIGINT NOT NULL REFERENCES players(id),
    away_team VARCHAR(100),
    away_player_id BIGINT NOT NULL REFERENCES players(id),

    status VARCHAR(20) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN (
            'scheduled', 'live', 'completed',
            'postponed', 'cancelled', 'unknown'
        )),

    home_score INTEGER,
    away_score INTEGER,

    -- Legacy observation values remain for existing imports and repositories.
    spread_line NUMERIC(8,2),
    away_spread_line NUMERIC(8,2),
    total_line NUMERIC(8,2),
    home_moneyline NUMERIC(10,3),
    away_moneyline NUMERIC(10,3),
    home_spread_odds NUMERIC(10,3),
    away_spread_odds NUMERIC(10,3),
    over_odds NUMERIC(10,3),
    under_odds NUMERIC(10,3),

    data_source VARCHAR(20) NOT NULL DEFAULT 'h2hgg'
        CHECK (data_source IN (
            'h2hgg', 'aceodds', 'manual', 'synthetic'
        )),

    is_synthetic BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_matches_different_players
        CHECK (home_player_id <> away_player_id),

    CONSTRAINT ck_matches_nonnegative_scores
        CHECK (
            (home_score IS NULL OR home_score >= 0)
            AND (away_score IS NULL OR away_score >= 0)
        ),

    CONSTRAINT ck_completed_matches_have_scores
        CHECK (
            status <> 'completed'
            OR (
                home_score IS NOT NULL
                AND away_score IS NOT NULL
            )
        ),

    CONSTRAINT uq_matches_fixture
        UNIQUE (match_time, home_player_id, away_player_id)
);

-- Detect reversed-orientation duplicates without deleting data.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM matches a
        JOIN matches b
          ON a.match_time = b.match_time
         AND a.home_player_id = b.away_player_id
         AND a.away_player_id = b.home_player_id
         AND a.id < b.id
    ) THEN
        RAISE EXCEPTION
            'Reversed-orientation duplicate matches exist. Reconcile them before applying the canonical fixture index.';
    END IF;
END;
$$;

-- Canonical fixture index: prevents duplicates in either orientation.
-- Keep uq_matches_fixture for compatibility with existing constraints.
CREATE UNIQUE INDEX IF NOT EXISTS uq_matches_fixture_canonical
    ON matches (
        match_time,
        LEAST(home_player_id, away_player_id),
        GREATEST(home_player_id, away_player_id)
    );

-- =========================================================
-- Match source provenance
-- =========================================================

CREATE TABLE IF NOT EXISTS match_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL
        REFERENCES matches(id) ON DELETE CASCADE,

    source VARCHAR(20) NOT NULL
        CHECK (source IN ('h2hgg', 'aceodds', 'manual', 'synthetic')),

    source_event_id VARCHAR(200),
    source_url TEXT,
    source_match_key VARCHAR(300),
    source_updated_at TIMESTAMPTZ,

    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_checked_at TIMESTAMPTZ,

    raw_hash VARCHAR(128),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_match_source_key
        UNIQUE (match_id, source, source_match_key)
);

-- Event IDs must be unique per source if the provider guarantees that.
CREATE UNIQUE INDEX IF NOT EXISTS uq_match_sources_external_id
    ON match_sources (source, source_event_id)
    WHERE source_event_id IS NOT NULL;

-- Fail rather than silently discarding duplicate unkeyed provenance.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM match_sources
        WHERE source_event_id IS NULL
          AND source_match_key IS NULL
        GROUP BY match_id, source
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Duplicate unkeyed provenance rows exist. Reconcile them before applying the unique index.';
    END IF;
END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_match_sources_unkeyed
    ON match_sources (match_id, source)
    WHERE source_event_id IS NULL
      AND source_match_key IS NULL;

CREATE INDEX IF NOT EXISTS idx_match_sources_match
    ON match_sources (match_id, source);

CREATE INDEX IF NOT EXISTS idx_match_sources_last_seen
    ON match_sources (source, last_seen_at DESC);

-- Legacy observations are retained for repository and database compatibility.
CREATE TABLE IF NOT EXISTS odds_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    market_type VARCHAR(20) NOT NULL
        CHECK (market_type IN ('moneyline', 'spread', 'total')),
    outcome VARCHAR(20) NOT NULL
        CHECK (outcome IN ('home', 'away', 'over', 'under')),
    line NUMERIC(8,2),
    odds NUMERIC(10,3) NOT NULL CHECK (odds > 1.000 AND odds < 10000),
    source VARCHAR(20) NOT NULL DEFAULT 'h2hgg'
        CHECK (source IN ('h2hgg', 'aceodds', 'manual', 'synthetic')),
    is_synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_odds_market_outcome CHECK (
        (market_type IN ('moneyline', 'spread') AND outcome IN ('home', 'away'))
        OR (market_type = 'total' AND outcome IN ('over', 'under'))
    )
);

-- Match the migration sequence: preserve legacy rows while enforcing these
-- checks on new and updated rows. A bootstrap database starts empty, but
-- keeping the validation state consistent simplifies schema comparison.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'matches'::regclass
          AND conname = 'ck_completed_matches_decisive'
    ) THEN
        ALTER TABLE matches
            ADD CONSTRAINT ck_completed_matches_decisive
            CHECK (status <> 'completed' OR home_score <> away_score)
            NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'matches'::regclass
          AND conname = 'ck_matches_synthetic_source'
    ) THEN
        ALTER TABLE matches
            ADD CONSTRAINT ck_matches_synthetic_source
            CHECK (
                (data_source = 'synthetic' AND is_synthetic)
                OR (data_source <> 'synthetic' AND NOT is_synthetic)
            )
            NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'odds_history'::regclass
          AND conname = 'ck_odds_synthetic_source'
    ) THEN
        ALTER TABLE odds_history
            ADD CONSTRAINT ck_odds_synthetic_source
            CHECK (
                (source = 'synthetic' AND is_synthetic)
                OR (source <> 'synthetic' AND NOT is_synthetic)
            )
            NOT VALID;
    END IF;
END;
$$;

-- =========================================================
-- Match query indexes
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_matches_match_time
    ON matches (match_time);

CREATE INDEX IF NOT EXISTS idx_matches_status_time
    ON matches (status, match_time);

CREATE INDEX IF NOT EXISTS idx_matches_home_player
    ON matches (home_player_id, match_time DESC);

CREATE INDEX IF NOT EXISTS idx_matches_away_player
    ON matches (away_player_id, match_time DESC);

CREATE INDEX IF NOT EXISTS idx_odds_history_match_time
    ON odds_history (match_id, observed_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_odds_history_market
    ON odds_history (match_id, market_type, outcome, observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_odds_history_source_time
    ON odds_history (source, observed_at DESC);

-- Real, completed results for analytics and backtesting.
CREATE INDEX IF NOT EXISTS idx_matches_real_completed_time
    ON matches (match_time DESC)
    WHERE status = 'completed'
      AND is_synthetic = FALSE
      AND home_score IS NOT NULL
      AND away_score IS NOT NULL;

-- Convenient filtered dataset for prediction and analysis.
CREATE OR REPLACE VIEW real_completed_matches AS
SELECT *
FROM matches
WHERE status = 'completed'
  AND is_synthetic = FALSE
  AND data_source <> 'synthetic'
  AND home_score IS NOT NULL
  AND away_score IS NOT NULL
  AND home_score <> away_score;

-- =========================================================
-- Automatic updated_at maintenance
-- =========================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_players_updated_at ON players;

CREATE TRIGGER trg_players_updated_at
    BEFORE UPDATE ON players
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_matches_updated_at ON matches;

CREATE TRIGGER trg_matches_updated_at
    BEFORE UPDATE ON matches
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE OR REPLACE VIEW latest_match_odds AS
SELECT DISTINCT ON (oh.match_id, oh.market_type, oh.outcome)
    oh.match_id,
    m.match_time,
    hp.handle AS home_handle,
    ap.handle AS away_handle,
    oh.market_type,
    oh.outcome,
    oh.line,
    oh.odds,
    oh.source,
    oh.is_synthetic,
    oh.observed_at
FROM odds_history AS oh
JOIN matches AS m ON m.id = oh.match_id
JOIN players AS hp ON hp.id = m.home_player_id
JOIN players AS ap ON ap.id = m.away_player_id
ORDER BY oh.match_id, oh.market_type, oh.outcome, oh.observed_at DESC, oh.id DESC;

-- Immutable prediction snapshots and append-only result evaluations.
CREATE TABLE IF NOT EXISTS prediction_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    source VARCHAR(20)
        CHECK (source IS NULL OR source IN ('h2hgg', 'aceodds', 'manual')),
    source_event_id VARCHAR(200),
    prediction_run_id UUID NOT NULL,
    prediction_created_at TIMESTAMPTZ NOT NULL,
    home_player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE RESTRICT,
    away_player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE RESTRICT,
    predicted_winner_player_id BIGINT REFERENCES players(id) ON DELETE RESTRICT,
    supporting_statistics JSONB NOT NULL,
    sample_size INTEGER NOT NULL CHECK (sample_size >= 0),
    evidence_strength VARCHAR(10) NOT NULL
        CHECK (evidence_strength IN ('low', 'medium', 'high')),
    method_version VARCHAR(80) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'correct', 'incorrect', 'void', 'unable_to_evaluate'
        )),
    evaluated_at TIMESTAMPTZ,
    current_result_fingerprint CHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_prediction_run_fixture UNIQUE (match_id, prediction_run_id),
    CONSTRAINT ck_prediction_distinct_players CHECK (home_player_id <> away_player_id),
    CONSTRAINT ck_prediction_winner_is_participant CHECK (
        predicted_winner_player_id IS NULL
        OR predicted_winner_player_id IN (home_player_id, away_player_id)
    )
);

CREATE INDEX IF NOT EXISTS idx_prediction_records_match
    ON prediction_records (match_id, prediction_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_prediction_records_status
    ON prediction_records (status, prediction_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_prediction_records_method
    ON prediction_records (method_version, evidence_strength, prediction_created_at DESC);

CREATE TABLE IF NOT EXISTS prediction_evaluation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id BIGINT NOT NULL
        REFERENCES prediction_records(id) ON DELETE RESTRICT,
    result_fingerprint CHAR(64) NOT NULL,
    result_signature CHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL
        CHECK (status IN ('correct', 'incorrect', 'void', 'unable_to_evaluate')),
    result_status VARCHAR(20) NOT NULL,
    home_score INTEGER,
    away_score INTEGER,
    actual_winner_player_id BIGINT REFERENCES players(id) ON DELETE RESTRICT,
    result_available_at TIMESTAMPTZ,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (prediction_id, result_fingerprint),
    CHECK ((home_score IS NULL OR home_score >= 0)
        AND (away_score IS NULL OR away_score >= 0))
);

CREATE INDEX IF NOT EXISTS idx_prediction_events_history
    ON prediction_evaluation_events (prediction_id, evaluated_at DESC, id DESC);

CREATE OR REPLACE FUNCTION validate_prediction_fixture()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE fixture RECORD;
BEGIN
    SELECT match_time, status, is_synthetic, home_player_id, away_player_id
    INTO fixture FROM matches WHERE id = NEW.match_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Prediction target match does not exist';
    END IF;
    IF fixture.status <> 'scheduled' OR fixture.is_synthetic THEN
        RAISE EXCEPTION 'Only real scheduled fixtures may be recorded as predictions';
    END IF;
    IF NEW.prediction_created_at >= fixture.match_time THEN
        RAISE EXCEPTION 'Prediction timestamp must precede fixture start';
    END IF;
    IF NEW.home_player_id <> fixture.home_player_id
       OR NEW.away_player_id <> fixture.away_player_id THEN
        RAISE EXCEPTION 'Prediction participants do not match the fixture';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION protect_prediction_record_identity()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.match_id IS DISTINCT FROM NEW.match_id
       OR OLD.source IS DISTINCT FROM NEW.source
       OR OLD.source_event_id IS DISTINCT FROM NEW.source_event_id
       OR OLD.prediction_run_id IS DISTINCT FROM NEW.prediction_run_id
       OR OLD.prediction_created_at IS DISTINCT FROM NEW.prediction_created_at
       OR OLD.home_player_id IS DISTINCT FROM NEW.home_player_id
       OR OLD.away_player_id IS DISTINCT FROM NEW.away_player_id
       OR OLD.predicted_winner_player_id IS DISTINCT FROM NEW.predicted_winner_player_id
       OR OLD.supporting_statistics IS DISTINCT FROM NEW.supporting_statistics
       OR OLD.sample_size IS DISTINCT FROM NEW.sample_size
       OR OLD.evidence_strength IS DISTINCT FROM NEW.evidence_strength
       OR OLD.method_version IS DISTINCT FROM NEW.method_version
       OR OLD.created_at IS DISTINCT FROM NEW.created_at THEN
        RAISE EXCEPTION 'Prediction records are immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION protect_prediction_evaluation_history()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Prediction evaluation events are append-only';
END;
$$;

DROP TRIGGER IF EXISTS trg_prediction_fixture_valid ON prediction_records;
CREATE TRIGGER trg_prediction_fixture_valid
    BEFORE INSERT ON prediction_records
    FOR EACH ROW EXECUTE FUNCTION validate_prediction_fixture();
DROP TRIGGER IF EXISTS trg_prediction_records_immutable ON prediction_records;
CREATE TRIGGER trg_prediction_records_immutable
    BEFORE UPDATE ON prediction_records
    FOR EACH ROW EXECUTE FUNCTION protect_prediction_record_identity();
DROP TRIGGER IF EXISTS trg_prediction_evaluation_events_append_only
    ON prediction_evaluation_events;
CREATE TRIGGER trg_prediction_evaluation_events_append_only
    BEFORE UPDATE OR DELETE ON prediction_evaluation_events
    FOR EACH ROW EXECUTE FUNCTION protect_prediction_evaluation_history();

COMMIT;
